// The planning and the menu are finished and tested; `apply` (partitioning and formatting) and
// the GRUB binary are not, so nothing calls into here from the UI yet.
#![allow(dead_code)]

//! Multiboot: one stick, drop ISOs on it, pick one at boot.
//!
//! The Ventoy idea, which is a much better fit for a 58 GB stick than writing one 4 GB image and
//! wasting the rest. The layout:
//!
//! ```text
//!   partition 1   64 MB   FAT32   EFI System Partition - the bootloader lives here
//!   partition 2   rest    exFAT   "SKJFLASH" - you copy .iso files onto this one
//! ```
//!
//! The firmware boots `\EFI\BOOT\BOOTX64.EFI` from the ESP, which is GRUB2. GRUB scans the data
//! partition for images and builds the menu, then boots the chosen one with its loopback support,
//! so the ISO is never extracted or written over the whole drive.
//!
//! This module owns the planning and the generated config - the parts that can be checked without
//! a disk. Partitioning and formatting live behind `apply`, and the GRUB binaries are not shipped
//! carried inside the binary (see `BOOTX64_EFI`).

/// Disks are happiest when partitions start on a 1 MiB boundary: it suits every erase block size
/// that flash uses, and every alignment the firmware cares about.
const ALIGN: u64 = 1024 * 1024;

/// Big enough for GRUB plus a few themes, small enough nobody notices it is gone.
const ESP_SIZE: u64 = 64 * ALIGN;

/// The smallest stick worth doing this to: the ESP plus enough room for one small ISO.
pub const MIN_SIZE: u64 = ESP_SIZE + 512 * ALIGN;

/// What goes where on the drive, in bytes.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Layout {
    pub esp_offset: u64,
    pub esp_size: u64,
    pub data_offset: u64,
    pub data_size: u64,
}

impl Layout {
    pub fn esp_end(&self) -> u64 {
        self.esp_offset + self.esp_size
    }
    pub fn data_end(&self) -> u64 {
        self.data_offset + self.data_size
    }
}

/// Work out the layout for a drive of `disk_size` bytes.
///
/// The first megabyte is left alone for the GPT itself, and the last for its backup copy.
pub fn plan(disk_size: u64) -> Result<Layout, String> {
    if disk_size < MIN_SIZE {
        return Err(format!(
            "The drive is only {}; multiboot needs at least {}",
            crate::disk::human_size(disk_size),
            crate::disk::human_size(MIN_SIZE)
        ));
    }
    let esp_offset = ALIGN;
    let esp_size = ESP_SIZE;
    let data_offset = esp_offset + esp_size;
    // leave the last megabyte for the backup GPT, then round down to a whole megabyte
    let usable_end = (disk_size - ALIGN) & !(ALIGN - 1);
    let data_size = usable_end.saturating_sub(data_offset);
    if data_size < ALIGN {
        return Err("No room left for the data partition".into());
    }
    Ok(Layout { esp_offset, esp_size, data_offset, data_size })
}

/// The label the data partition gets, and what GRUB looks for.
pub const DATA_LABEL: &str = "SKJFLASH";

/// What GRUB runs at boot.
///
/// It walks every partition looking for the one labelled SKJFLASH, lists the images on it and
/// boots the chosen one through loopback, so the ISO stays a file. The three boot styles cover
/// what real images actually do: most Linux ISOs want their own kernel and initrd, many are happy
/// being chainloaded, and the rest fall back to the ISO's own EFI loader.
pub fn grub_cfg() -> String {
    format!(
        r#"# Generated by SKJ Flash. Edited copies are kept: this file is only written when the
# drive is prepared, never when images are added.

set timeout=10
set default=0

insmod part_gpt
insmod part_msdos
insmod exfat
insmod fat
insmod iso9660
insmod loopback
insmod search_label
insmod all_video
insmod gfxterm

if loadfont /boot/grub/fonts/unicode.pf2 ; then
  set gfxmode=auto
  terminal_output gfxterm
fi

search --no-floppy --label --set=data {label}

menuentry "SKJ Flash - pick an image" {{
  true
}}

# One entry per image found on the data partition.
for iso in ($data)/*.iso ($data)/isos/*.iso ($data)/ISO/*.iso; do
  if [ -f "$iso" ]; then
    regexp --set=name '.*/([^/]+)$' "$iso"
    menuentry "$name" "$iso" {{
      set file="$2"
      loopback loop "$file"
      # most Linux images: their own kernel, told where the ISO is
      if [ -f (loop)/casper/vmlinuz ]; then
        linux (loop)/casper/vmlinuz iso-scan/filename="$file" quiet splash
        initrd (loop)/casper/initrd
      elif [ -f (loop)/live/vmlinuz ]; then
        linux (loop)/live/vmlinuz findiso="$file" boot=live components quiet splash
        initrd (loop)/live/initrd.img
      elif [ -f (loop)/boot/x86_64/loader/linux ]; then
        linux (loop)/boot/x86_64/loader/linux iso-scan/filename="$file"
        initrd (loop)/boot/x86_64/loader/initrd
      elif [ -f (loop)/EFI/BOOT/BOOTX64.EFI ]; then
        # anything with its own EFI loader, Windows installers included
        chainloader (loop)/EFI/BOOT/BOOTX64.EFI
      else
        echo "SKJ Flash does not know how to boot this image yet."
        echo "Press any key to go back."
        read
      fi
    }}
  fi
done

menuentry "Reboot" {{ reboot }}
menuentry "Shut down" {{ halt }}
"#,
        label = DATA_LABEL
    )
}

/// The bootloader, carried inside the binary so a prepared drive needs nothing downloaded.
///
/// GRUB2, built by `.github/workflows/grub.yml` with `grub-mkstandalone` from the distribution's
/// own GRUB source, with exactly the modules `grub_cfg` uses baked in. SKJ Flash cannot compile
/// GRUB, and shipping somebody else's prebuilt blob would mean trusting a binary nobody can
/// account for — building it in the open is also what makes the GPL obligation honest. To
/// refresh it, run that workflow and drop the artifact back here.
pub const BOOTX64_EFI: &[u8] = include_bytes!("../assets/boot/BOOTX64.EFI");

pub const BOOTLOADER_NOTE: &str =
    "The bootloader is GRUB2, built from source by this project's own workflow.";

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_small_stick_is_refused_rather_than_half_prepared() {
        assert!(plan(0).is_err());
        assert!(plan(16 * 1024 * 1024).is_err());
        assert!(plan(MIN_SIZE - 1).is_err());
        assert!(plan(MIN_SIZE).is_ok());
    }

    #[test]
    fn everything_lands_on_a_megabyte_boundary() {
        // flash erase blocks and firmware both care; misalignment costs speed and sometimes boots
        for size in [MIN_SIZE, 2 * 1024u64.pow(3), 58_000_000_000, 1 << 40] {
            let l = plan(size).expect("should plan");
            for v in [l.esp_offset, l.esp_size, l.data_offset, l.data_size] {
                assert_eq!(v % ALIGN, 0, "{v} is not megabyte aligned for a {size} byte disk");
            }
        }
    }

    #[test]
    fn partitions_do_not_overlap_or_run_off_the_end() {
        let size = 58_000_000_000u64;
        let l = plan(size).unwrap();
        assert!(l.esp_offset >= ALIGN, "the GPT needs the first megabyte");
        assert_eq!(l.data_offset, l.esp_end(), "no gap, no overlap");
        assert!(l.data_end() <= size - ALIGN, "the backup GPT needs the last megabyte");
    }

    #[test]
    fn the_data_partition_gets_nearly_the_whole_stick() {
        let size = 58 * 1024u64.pow(3);
        let l = plan(size).unwrap();
        // everything except the ESP and the two megabytes of GPT
        assert!(l.data_size > size - ESP_SIZE - 4 * ALIGN);
    }

    #[test]
    fn the_menu_looks_for_the_right_drive() {
        let cfg = grub_cfg();
        assert!(cfg.contains(DATA_LABEL), "it has to find the data partition by label");
        assert!(cfg.contains("loopback loop"), "images are booted as files, not extracted");
        assert!(cfg.contains("iso-scan/filename"), "Linux images need to be told where the ISO is");
        assert!(cfg.contains("chainloader"), "images with their own EFI loader need chainloading");
    }

    #[test]
    fn the_menu_has_balanced_braces() {
        // a stray brace in grub.cfg is a drive that boots to a GRUB rescue prompt
        let cfg = grub_cfg();
        let opens = cfg.matches('{').count();
        let closes = cfg.matches('}').count();
        assert_eq!(opens, closes, "unbalanced braces in grub.cfg");
    }
}

// ───────────────────────── preparing a drive ─────────────────────────

/// The disk number Windows knows a device by: `\.\PhysicalDrive2` -> 2.
pub fn disk_number(path: &str) -> Option<u32> {
    path.rsplit("PhysicalDrive").next()?.parse().ok()
}

/// The diskpart script that lays the drive out.
///
/// Partitioning and formatting go through diskpart rather than IOCTL_DISK_SET_DRIVE_LAYOUT_EX and
/// FormatEx. Those are the "proper" way and are what a Linux and macOS port will need anyway, but
/// they are several hundred lines of unsafe code that cannot be exercised without destroying a
/// real disk. diskpart is maintained by Microsoft, does exactly this job, and lets the part that
/// *can* be checked - which disk, which sizes, which labels - stay ordinary testable code.
///
/// `select disk` is by number, and the number comes from a Device that already passed the safety
/// rules, so this cannot be aimed at an uninspected disk.
pub fn diskpart_script(disk: u32, esp_mb: u64) -> String {
    format!(
        "select disk {disk}\n\
         clean\n\
         convert gpt\n\
         create partition efi size={esp_mb}\n\
         format fs=fat32 quick label=SKJBOOT\n\
         assign\n\
         create partition primary\n\
         format fs=exfat quick label={label}\n\
         assign\n\
         exit\n",
        disk = disk,
        esp_mb = esp_mb,
        label = DATA_LABEL
    )
}

/// Lay the drive out for multiboot. Erases everything on it.
pub fn prepare(dev: &crate::disk::Device, mut progress: impl FnMut(&str)) -> Result<(), String> {
    if dev.system {
        return Err("Refusing: that is the disk the system runs from".into());
    }
    let layout = plan(dev.size)?;
    let disk = disk_number(&dev.path).ok_or_else(|| format!("Cannot tell which disk {} is", dev.path))?;

    progress("Partitioning and formatting…");
    let script = diskpart_script(disk, layout.esp_size / (1024 * 1024));
    run_diskpart(&script)?;

    progress("Installing the bootloader…");
    install_bootloader()?;

    progress("Writing the boot menu…");
    write_grub_cfg()?;

    progress("Ready.");
    Ok(())
}

#[cfg(windows)]
fn run_diskpart(script: &str) -> Result<(), String> {
    use std::io::Write;
    // diskpart only reads a script from a file, not from stdin
    let dir = std::env::temp_dir();
    let path = dir.join(format!("skj-flash-{}.txt", std::process::id()));
    {
        let mut f = std::fs::File::create(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        f.write_all(script.as_bytes()).map_err(|e| format!("{}: {e}", path.display()))?;
    }
    let out = std::process::Command::new("diskpart")
        .arg("/s")
        .arg(&path)
        .output()
        .map_err(|e| format!("Could not run diskpart: {e}"));
    let _ = std::fs::remove_file(&path);
    let out = out?;
    if out.status.success() {
        Ok(())
    } else {
        // diskpart says what went wrong on stdout, not stderr
        let said = String::from_utf8_lossy(&out.stdout);
        let tail: Vec<&str> = said.lines().filter(|l| !l.trim().is_empty()).rev().take(4).collect();
        Err(format!("diskpart failed: {}", tail.into_iter().rev().collect::<Vec<_>>().join(" / ")))
    }
}

#[cfg(not(windows))]
fn run_diskpart(_script: &str) -> Result<(), String> {
    Err("Preparing a drive is only implemented on Windows so far".into())
}

/// Put GRUB where the firmware looks for it: `\EFI\BOOT\BOOTX64.EFI` on the ESP.
///
/// That exact path is the removable-media fallback every UEFI firmware tries, which is why this
/// boots without registering anything in the machine's NVRAM.
#[cfg(windows)]
fn install_bootloader() -> Result<(), String> {
    let esp = find_labelled("SKJBOOT")
        .ok_or("Could not find the SKJBOOT partition after formatting it")?;
    let dir = std::path::Path::new(&esp).join("EFI").join("BOOT");
    std::fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    let efi = dir.join("BOOTX64.EFI");
    std::fs::write(&efi, BOOTX64_EFI).map_err(|e| format!("{}: {e}", efi.display()))?;

    // GRUB looks beside itself for its config as well as on the data partition, so a copy here
    // means the menu still comes up if the data partition is ever reformatted by hand.
    let gdir = std::path::Path::new(&esp).join("boot").join("grub");
    std::fs::create_dir_all(&gdir).map_err(|e| format!("{}: {e}", gdir.display()))?;
    let cfg = gdir.join("grub.cfg");
    std::fs::write(&cfg, grub_cfg()).map_err(|e| format!("{}: {e}", cfg.display()))
}

#[cfg(not(windows))]
fn install_bootloader() -> Result<(), String> {
    Err("Preparing a drive is only implemented on Windows so far".into())
}

/// Put grub.cfg on the freshly formatted data partition.
#[cfg(windows)]
fn write_grub_cfg() -> Result<(), String> {
    let drive = find_labelled(DATA_LABEL)
        .ok_or_else(|| format!("Could not find the {DATA_LABEL} partition after formatting it"))?;
    let dir = std::path::Path::new(&drive).join("boot").join("grub");
    std::fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    let cfg = dir.join("grub.cfg");
    std::fs::write(&cfg, grub_cfg()).map_err(|e| format!("{}: {e}", cfg.display()))
}

#[cfg(not(windows))]
fn write_grub_cfg() -> Result<(), String> {
    Err("Preparing a drive is only implemented on Windows so far".into())
}

/// Which drive letter carries a volume with this label.
#[cfg(windows)]
fn find_labelled(label: &str) -> Option<String> {
    use std::os::windows::ffi::OsStrExt;
    use windows::core::PCWSTR;
    use windows::Win32::Storage::FileSystem::GetVolumeInformationW;

    for c in b'A'..=b'Z' {
        let root = format!("{}:\\", c as char);
        let wide: Vec<u16> = std::ffi::OsStr::new(&root).encode_wide().chain(Some(0)).collect();
        let mut name = [0u16; 64];
        let ok = unsafe {
            GetVolumeInformationW(PCWSTR(wide.as_ptr()), Some(&mut name), None, None, None, None)
        };
        if ok.is_ok() {
            let end = name.iter().position(|&x| x == 0).unwrap_or(0);
            if String::from_utf16_lossy(&name[..end]).eq_ignore_ascii_case(label) {
                return Some(format!("{}:\\", c as char));
            }
        }
    }
    None
}

#[cfg(test)]
mod prepare_tests {
    use super::*;

    #[test]
    fn the_disk_number_comes_out_of_the_device_path() {
        assert_eq!(disk_number(r"\.\PhysicalDrive0"), Some(0));
        assert_eq!(disk_number(r"\.\PhysicalDrive7"), Some(7));
        assert_eq!(disk_number(r"\.\PhysicalDrive12"), Some(12));
        assert_eq!(disk_number("/dev/sdb"), None);
        assert_eq!(disk_number(""), None);
    }

    #[test]
    fn the_script_targets_the_disk_it_was_given() {
        let s = diskpart_script(3, 64);
        assert!(s.starts_with("select disk 3\n"), "the very first line has to pick the disk");
        assert!(s.contains("\nclean\n"), "an old layout has to go first");
        assert!(s.contains("convert gpt"));
    }

    #[test]
    fn the_script_makes_both_partitions_the_right_way() {
        let s = diskpart_script(1, 64);
        assert!(s.contains("create partition efi size=64"));
        assert!(s.contains("format fs=fat32 quick label=SKJBOOT"), "firmware only reads FAT32");
        assert!(s.contains("create partition primary"));
        assert!(s.contains(&format!("format fs=exfat quick label={DATA_LABEL}")), "exFAT so a 4 GB+ ISO fits");
    }

    #[test]
    fn the_esp_size_follows_the_plan() {
        let l = plan(58 * 1024u64.pow(3)).unwrap();
        let s = diskpart_script(1, l.esp_size / (1024 * 1024));
        assert!(s.contains("size=64"), "the script and the plan must agree");
    }

    #[test]
    fn the_script_ends_cleanly() {
        assert!(diskpart_script(0, 64).ends_with("exit\n"), "diskpart should not be left waiting");
    }
}

#[cfg(test)]
mod bootloader_tests {
    use super::*;

    #[test]
    fn the_bootloader_is_a_real_efi_binary() {
        // a drive that boots to nothing is the worst failure this program has, so check the
        // shipped blob really is what the firmware will accept
        assert!(BOOTX64_EFI.len() > 500_000, "too small to be GRUB with its modules");
        assert_eq!(&BOOTX64_EFI[..2], b"MZ", "not a PE image");
        // the PE header offset lives at 0x3C, and must point at "PE\0\0"
        let off = u32::from_le_bytes(BOOTX64_EFI[0x3C..0x40].try_into().unwrap()) as usize;
        assert_eq!(&BOOTX64_EFI[off..off + 4], b"PE\0\0", "no PE signature");
        // 0x8664 = x86-64, which is what BOOTX64.EFI has to be
        let machine = u16::from_le_bytes(BOOTX64_EFI[off + 4..off + 6].try_into().unwrap());
        assert_eq!(machine, 0x8664, "not an x86-64 binary");
        // subsystem 10 = EFI application
        let subsystem = u16::from_le_bytes(BOOTX64_EFI[off + 24 + 68..off + 24 + 70].try_into().unwrap());
        assert_eq!(subsystem, 10, "not an EFI application");
    }
}
