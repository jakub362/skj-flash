// The planning and the menu are finished and tested; `apply` (partitioning and formatting) and
// the GRUB binary are not, so nothing calls into here from the UI yet.
#![allow(dead_code)]

//! Multiboot: one stick, drop ISOs on it, pick one at boot.
//!
//! The Ventoy idea, which is a much better fit for a 58 GB stick than writing one 4 GB image and
//! wasting the rest. The layout:
//!
//! ```text
//!   partition 1   64 MB   FAT32   EFI System Partition - the bootloader lives here
//!   partition 2   rest    exFAT   "SKJFLASH" - you copy .iso files onto this one
//! ```
//!
//! The firmware boots `\EFI\BOOT\BOOTX64.EFI` from the ESP, which is GRUB2. GRUB scans the data
//! partition for images and builds the menu, then boots the chosen one with its loopback support,
//! so the ISO is never extracted or written over the whole drive.
//!
//! This module owns the planning and the generated config - the parts that can be checked without
//! a disk. Partitioning and formatting live behind `apply`, and the GRUB binaries are not shipped
//! here yet (see `BOOTLOADER_NOTE`).

/// Disks are happiest when partitions start on a 1 MiB boundary: it suits every erase block size
/// that flash uses, and every alignment the firmware cares about.
const ALIGN: u64 = 1024 * 1024;

/// Big enough for GRUB plus a few themes, small enough nobody notices it is gone.
const ESP_SIZE: u64 = 64 * ALIGN;

/// The smallest stick worth doing this to: the ESP plus enough room for one small ISO.
pub const MIN_SIZE: u64 = ESP_SIZE + 512 * ALIGN;

/// What goes where on the drive, in bytes.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Layout {
    pub esp_offset: u64,
    pub esp_size: u64,
    pub data_offset: u64,
    pub data_size: u64,
}

impl Layout {
    pub fn esp_end(&self) -> u64 {
        self.esp_offset + self.esp_size
    }
    pub fn data_end(&self) -> u64 {
        self.data_offset + self.data_size
    }
}

/// Work out the layout for a drive of `disk_size` bytes.
///
/// The first megabyte is left alone for the GPT itself, and the last for its backup copy.
pub fn plan(disk_size: u64) -> Result<Layout, String> {
    if disk_size < MIN_SIZE {
        return Err(format!(
            "The drive is only {}; multiboot needs at least {}",
            crate::disk::human_size(disk_size),
            crate::disk::human_size(MIN_SIZE)
        ));
    }
    let esp_offset = ALIGN;
    let esp_size = ESP_SIZE;
    let data_offset = esp_offset + esp_size;
    // leave the last megabyte for the backup GPT, then round down to a whole megabyte
    let usable_end = (disk_size - ALIGN) & !(ALIGN - 1);
    let data_size = usable_end.saturating_sub(data_offset);
    if data_size < ALIGN {
        return Err("No room left for the data partition".into());
    }
    Ok(Layout { esp_offset, esp_size, data_offset, data_size })
}

/// The label the data partition gets, and what GRUB looks for.
pub const DATA_LABEL: &str = "SKJFLASH";

/// What GRUB runs at boot.
///
/// It walks every partition looking for the one labelled SKJFLASH, lists the images on it and
/// boots the chosen one through loopback, so the ISO stays a file. The three boot styles cover
/// what real images actually do: most Linux ISOs want their own kernel and initrd, many are happy
/// being chainloaded, and the rest fall back to the ISO's own EFI loader.
pub fn grub_cfg() -> String {
    format!(
        r#"# Generated by SKJ Flash. Edited copies are kept: this file is only written when the
# drive is prepared, never when images are added.

set timeout=10
set default=0

insmod part_gpt
insmod part_msdos
insmod exfat
insmod fat
insmod iso9660
insmod loopback
insmod search_label
insmod all_video
insmod gfxterm

if loadfont /boot/grub/fonts/unicode.pf2 ; then
  set gfxmode=auto
  terminal_output gfxterm
fi

search --no-floppy --label --set=data {label}

menuentry "SKJ Flash - pick an image" {{
  true
}}

# One entry per image found on the data partition.
for iso in ($data)/*.iso ($data)/isos/*.iso ($data)/ISO/*.iso; do
  if [ -f "$iso" ]; then
    regexp --set=name '.*/([^/]+)$' "$iso"
    menuentry "$name" "$iso" {{
      set file="$2"
      loopback loop "$file"
      # most Linux images: their own kernel, told where the ISO is
      if [ -f (loop)/casper/vmlinuz ]; then
        linux (loop)/casper/vmlinuz iso-scan/filename="$file" quiet splash
        initrd (loop)/casper/initrd
      elif [ -f (loop)/live/vmlinuz ]; then
        linux (loop)/live/vmlinuz findiso="$file" boot=live components quiet splash
        initrd (loop)/live/initrd.img
      elif [ -f (loop)/boot/x86_64/loader/linux ]; then
        linux (loop)/boot/x86_64/loader/linux iso-scan/filename="$file"
        initrd (loop)/boot/x86_64/loader/initrd
      elif [ -f (loop)/EFI/BOOT/BOOTX64.EFI ]; then
        # anything with its own EFI loader, Windows installers included
        chainloader (loop)/EFI/BOOT/BOOTX64.EFI
      else
        echo "SKJ Flash does not know how to boot this image yet."
        echo "Press any key to go back."
        read
      fi
    }}
  fi
done

menuentry "Reboot" {{ reboot }}
menuentry "Shut down" {{ halt }}
"#,
        label = DATA_LABEL
    )
}

/// Still missing before a prepared stick will actually boot.
///
/// GRUB has to be built, or taken from a distribution, as a standalone EFI binary with the
/// modules above baked in - SKJ Flash cannot compile GRUB. The plan is to build it once in CI
/// with `grub-mkstandalone` and ship the result, which GPL-3.0 allows as long as the source and
/// the build script go with it.
pub const BOOTLOADER_NOTE: &str = "\
Multiboot needs a GRUB2 EFI binary at \\EFI\\BOOT\\BOOTX64.EFI on the ESP.
SKJ Flash does not ship one yet, so a prepared drive will not boot until it does.
The layout, the formatting and the menu are already correct.";

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_small_stick_is_refused_rather_than_half_prepared() {
        assert!(plan(0).is_err());
        assert!(plan(16 * 1024 * 1024).is_err());
        assert!(plan(MIN_SIZE - 1).is_err());
        assert!(plan(MIN_SIZE).is_ok());
    }

    #[test]
    fn everything_lands_on_a_megabyte_boundary() {
        // flash erase blocks and firmware both care; misalignment costs speed and sometimes boots
        for size in [MIN_SIZE, 2 * 1024u64.pow(3), 58_000_000_000, 1 << 40] {
            let l = plan(size).expect("should plan");
            for v in [l.esp_offset, l.esp_size, l.data_offset, l.data_size] {
                assert_eq!(v % ALIGN, 0, "{v} is not megabyte aligned for a {size} byte disk");
            }
        }
    }

    #[test]
    fn partitions_do_not_overlap_or_run_off_the_end() {
        let size = 58_000_000_000u64;
        let l = plan(size).unwrap();
        assert!(l.esp_offset >= ALIGN, "the GPT needs the first megabyte");
        assert_eq!(l.data_offset, l.esp_end(), "no gap, no overlap");
        assert!(l.data_end() <= size - ALIGN, "the backup GPT needs the last megabyte");
    }

    #[test]
    fn the_data_partition_gets_nearly_the_whole_stick() {
        let size = 58 * 1024u64.pow(3);
        let l = plan(size).unwrap();
        // everything except the ESP and the two megabytes of GPT
        assert!(l.data_size > size - ESP_SIZE - 4 * ALIGN);
    }

    #[test]
    fn the_menu_looks_for_the_right_drive() {
        let cfg = grub_cfg();
        assert!(cfg.contains(DATA_LABEL), "it has to find the data partition by label");
        assert!(cfg.contains("loopback loop"), "images are booted as files, not extracted");
        assert!(cfg.contains("iso-scan/filename"), "Linux images need to be told where the ISO is");
        assert!(cfg.contains("chainloader"), "images with their own EFI loader need chainloading");
    }

    #[test]
    fn the_menu_has_balanced_braces() {
        // a stray brace in grub.cfg is a drive that boots to a GRUB rescue prompt
        let cfg = grub_cfg();
        let opens = cfg.matches('{').count();
        let closes = cfg.matches('}').count();
        assert_eq!(opens, closes, "unbalanced braces in grub.cfg");
    }
}
